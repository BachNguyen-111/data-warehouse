/*
===============================================================================
DDL Script: Create Gold Tables
===============================================================================
Script Purpose:
    This script creates the tables of the Gold layer (Star Schema):
        - gold.dim_customers  (SCD Type 1: changes overwrite the old values)
        - gold.dim_products   (SCD Type 2: changes create a new version)
        - gold.dim_date       (calendar, one row per day)
        - gold.fact_sales     (sales transactions)

    Gold is stored as TABLES (not views) so the warehouse can remember
    history and keep surrogate keys stable between loads.
    The tables are filled by the stored procedure gold.load_gold.

WARNING:
    Running this script DROPS the Gold tables, including all product history.
    Run it once to set up Gold, then use: EXEC gold.load_gold;
===============================================================================
*/

-- =============================================================================
-- Drop old objects (fact first, because it references the dimensions)
-- Gold used to be views, so old views are dropped too.
-- =============================================================================
IF OBJECT_ID('gold.fact_sales', 'V') IS NOT NULL DROP VIEW gold.fact_sales;
IF OBJECT_ID('gold.fact_sales', 'U') IS NOT NULL DROP TABLE gold.fact_sales;
IF OBJECT_ID('gold.dim_customers', 'V') IS NOT NULL DROP VIEW gold.dim_customers;
IF OBJECT_ID('gold.dim_customers', 'U') IS NOT NULL DROP TABLE gold.dim_customers;
IF OBJECT_ID('gold.dim_products', 'V') IS NOT NULL DROP VIEW gold.dim_products;
IF OBJECT_ID('gold.dim_products', 'U') IS NOT NULL DROP TABLE gold.dim_products;
IF OBJECT_ID('gold.dim_date', 'V') IS NOT NULL DROP VIEW gold.dim_date;
IF OBJECT_ID('gold.dim_date', 'U') IS NOT NULL DROP TABLE gold.dim_date;
GO

-- =============================================================================
-- Create Dimension: gold.dim_customers  (SCD Type 1)
-- =============================================================================
CREATE TABLE gold.dim_customers (
    customer_key     INT IDENTITY(1,1) NOT NULL, -- Surrogate key, generated by the warehouse
    customer_id      INT           NOT NULL,     -- Business key from CRM
    customer_number  NVARCHAR(50),
    first_name       NVARCHAR(50),
    last_name        NVARCHAR(50),
    country          NVARCHAR(50),
    marital_status   NVARCHAR(50),
    gender           NVARCHAR(50),
    birthdate        DATE,
    create_date      DATE,
    dwh_insert_date  DATETIME2 NOT NULL DEFAULT GETDATE(), -- When the row was first loaded
    dwh_update_date  DATETIME2 NOT NULL DEFAULT GETDATE(), -- When the row was last changed
    CONSTRAINT pk_dim_customers PRIMARY KEY (customer_key),
    CONSTRAINT uq_dim_customers_customer_id UNIQUE (customer_id)
);
GO

-- =============================================================================
-- Create Dimension: gold.dim_products  (SCD Type 2)
-- =============================================================================
-- One row per product VERSION. When a tracked attribute changes, the load
-- closes the current version and opens a new one.
--   valid_from / valid_to : period the version applies to (used to match sales)
--   is_current            : 1 = the version that is valid now
--   version_number        : 1 = first version, 2 = second, ...
-- =============================================================================
CREATE TABLE gold.dim_products (
    product_key      INT IDENTITY(1,1) NOT NULL, -- Surrogate key (one per version)
    product_id       INT,
    product_number   NVARCHAR(50)  NOT NULL,     -- Business key (same for all versions)
    product_name     NVARCHAR(50),
    category_id      NVARCHAR(50),
    category         NVARCHAR(50),
    subcategory      NVARCHAR(50),
    maintenance      NVARCHAR(50),
    cost             INT,
    product_line     NVARCHAR(50),
    start_date       DATE,                       -- Start date as delivered by the source
    valid_from       DATE          NOT NULL,
    valid_to         DATE          NOT NULL,     -- 9999-12-31 for the current version
    is_current       INT           NOT NULL,
    version_number   INT           NOT NULL,
    dwh_insert_date  DATETIME2     NOT NULL DEFAULT GETDATE(),
    dwh_update_date  DATETIME2     NOT NULL DEFAULT GETDATE(),
    CONSTRAINT pk_dim_products PRIMARY KEY (product_key),
    CONSTRAINT ck_dim_products_period CHECK (valid_from <= valid_to),
    CONSTRAINT ck_dim_products_is_current CHECK (is_current IN (0, 1))
);
GO

-- A product can only have ONE current version (filtered unique index)
CREATE UNIQUE INDEX ux_dim_products_current
    ON gold.dim_products (product_number)
    WHERE is_current = 1;
GO

-- =============================================================================
-- Create Dimension: gold.dim_date
-- =============================================================================
-- One row per calendar day + one 'Unknown' row (date_key = -1) for missing dates.
-- =============================================================================
CREATE TABLE gold.dim_date (
    date_key            INT          NOT NULL, -- Smart key: YYYYMMDD
    full_date           DATE,
    day_of_month        INT,
    day_of_year         INT,
    day_of_week         INT,                   -- 1 = Monday ... 7 = Sunday
    day_name            NVARCHAR(30),
    day_name_short      NVARCHAR(3),
    day_type            NVARCHAR(7),           -- 'Weekday' / 'Weekend'
    week_of_year        INT,                   -- ISO week
    month_number        INT,
    month_name          NVARCHAR(30),
    month_name_short    NVARCHAR(3),
    quarter_number      INT,
    quarter_name        NVARCHAR(3),
    year                INT,
    year_month          NVARCHAR(7),           -- 'YYYY-MM'
    first_day_of_month  DATE,
    last_day_of_month   DATE,
    CONSTRAINT pk_dim_date PRIMARY KEY (date_key)
);
GO

-- =============================================================================
-- Create Fact Table: gold.fact_sales
-- =============================================================================
CREATE TABLE gold.fact_sales (
    order_number       NVARCHAR(50),
    product_key        INT,
    customer_key       INT,
    order_date_key     INT NOT NULL,
    shipping_date_key  INT NOT NULL,
    due_date_key       INT NOT NULL,
    order_date         DATE,
    shipping_date      DATE,
    due_date           DATE,
    sales_amount       INT,
    quantity           INT,
    price              INT,
    dwh_insert_date    DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT fk_fact_sales_product   FOREIGN KEY (product_key)       REFERENCES gold.dim_products (product_key),
    CONSTRAINT fk_fact_sales_customer  FOREIGN KEY (customer_key)      REFERENCES gold.dim_customers (customer_key),
    CONSTRAINT fk_fact_sales_order_dt  FOREIGN KEY (order_date_key)    REFERENCES gold.dim_date (date_key),
    CONSTRAINT fk_fact_sales_ship_dt   FOREIGN KEY (shipping_date_key) REFERENCES gold.dim_date (date_key),
    CONSTRAINT fk_fact_sales_due_dt    FOREIGN KEY (due_date_key)      REFERENCES gold.dim_date (date_key)
);
GO
